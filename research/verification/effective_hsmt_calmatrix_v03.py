def stieltjes(
    measure: OperatorSpectralMeasure,
    z: ArrayLike,
    n: int = 3000,
) -> np.ndarray:
    z = np.asarray(z, dtype=complex)
    if measure.stieltjes is not None:
        out = np.asarray(measure.stieltjes(z), dtype=complex)
        expected = z.shape + (measure.dim, measure.dim)
        if out.shape != expected:
            raise ValueError(f"analytic Stieltjes returned {out.shape}, expected {expected}")
        return out

    a, b = measure.support
    if measure.density is not None and (not np.isfinite(a) or not np.isfinite(b)):
        raise ValueError("numerical Stieltjes transform needs finite support")

    flat = z.ravel()
    out = np.zeros((flat.size, measure.dim, measure.dim), dtype=complex)

    if measure.density is not None and b > a:
        x = np.linspace(a, b, n)
        rho = np.asarray(measure.density(x), dtype=complex)
        if rho.shape != (n, measure.dim, measure.dim):
            raise ValueError("density returned wrong shape")
        for i, zi in enumerate(flat):
            out[i] += np.trapezoid(
                rho / (zi - x)[:, None, None], x, axis=0
            )

    for e, W in measure.atoms:
        out += W[None, :, :] / (flat[:, None, None] - e)

    return out.reshape(z.shape + (measure.dim, measure.dim))


def sigma(
    measure: OperatorSpectralMeasure,
    z: ArrayLike,
    scale: float = 1.0,
    n: int = 3000,
) -> np.ndarray:
    if scale < 0:
        raise ValueError("scale must be nonnegative for a positive spectral weight")
    return scale * stieltjes(measure, z, n=n)


def propagator(
    H_v: ArrayLike,
    measure: OperatorSpectralMeasure,
    z: ArrayLike,
    scale: float = 1.0,
) -> np.ndarray:
    H = np.asarray(H_v, dtype=complex)
    if H.shape != (measure.dim, measure.dim):
        raise ValueError("H_v dimension does not match the measure")
    if not _is_hermitian(H):
        raise ValueError("H_v must be Hermitian")

    z = np.asarray(z, dtype=complex)
    S = sigma(measure, z, scale=scale)
    flat_z = z.ravel()
    flat_S = S.reshape((-1, measure.dim, measure.dim))
    out = np.empty_like(flat_S)
    I = np.eye(measure.dim, dtype=complex)
    for i, zi in enumerate(flat_z):
        out[i] = np.linalg.inv(zi * I - H - flat_S[i])
    return out.reshape(z.shape + (measure.dim, measure.dim))


def visible_spectral_density(
    H_v: ArrayLike,
    measure: OperatorSpectralMeasure,
    E: ArrayLike,
    scale: float = 1.0,
    eta: float = 1e-4,
) -> np.ndarray:
    G = propagator(
        H_v, measure, np.asarray(E, dtype=float) + 1j * eta, scale=scale
    )
    # A(E) = -(1/pi) Im G, with matrix Im.
    return -_imaginary_part(G) / np.pi


def memory(
    measure: OperatorSpectralMeasure,
    t: ArrayLike,
    n: int = 4000,
) -> np.ndarray:
    """K(t)=∫exp(-iEt)dM(E), including atomic terms."""
    t = np.asarray(t, dtype=float)
    flat_t = t.ravel()
    out = np.zeros((flat_t.size, measure.dim, measure.dim), dtype=complex)
    a, b = measure.support

    if measure.density is not None:
        if not np.isfinite(a) or not np.isfinite(b):
            raise ValueError("numerical memory kernel needs finite support")
        if b > a:
            x = np.linspace(a, b, n)
            rho = np.asarray(measure.density(x), dtype=complex)
            for i, ti in enumerate(flat_t):
                phase = np.exp(-1j * x * ti)
                out[i] += np.trapezoid(
                    phase[:, None, None] * rho, x, axis=0
                )

    for e, W in measure.atoms:
        out += np.exp(-1j * e * flat_t)[:, None, None] * W[None, :, :]

    return out.reshape(t.shape + (measure.dim, measure.dim))


def inverse_sigma(
    G: ArrayLike,
    z: ArrayLike,
    H_v: ArrayLike,
) -> np.ndarray:
    """Recover Sigma(z)=zI-H_V-G(z)^{-1}."""
    G = np.asarray(G, dtype=complex)
    z = np.asarray(z, dtype=complex)
    H = np.asarray(H_v, dtype=complex)
    dim = H.shape[0]
    if G.shape[-2:] != (dim, dim):
        raise ValueError("G and H_v dimensions do not match")
    if G.shape[:-2] != z.shape:
        raise ValueError("z shape must match G batch shape")

    flat_G = G.reshape((-1, dim, dim))
    flat_z = z.ravel()
    out = np.empty_like(flat_G)
    I = np.eye(dim, dtype=complex)
    for i, zi in enumerate(flat_z):
        out[i] = zi * I - H - np.linalg.inv(flat_G[i])
    return out.reshape(G.shape)


# ---------------------------------------------------------------------------
# Visible coupled/cyclic subspace
# ---------------------------------------------------------------------------

def visible_coupled_basis(
    H_v: ArrayLike,
    total_weight: ArrayLike,
    tol: float = 1e-10,
) -> np.ndarray:
    """Basis for span{H_V^k range(M0)} in the finite visible space.

    This is a visible-space coupled-subspace diagnostic, not the full hidden
    cyclic realization.
    """
    H = np.asarray(H_v, dtype=complex)
    M0 = _hermitian_part(np.asarray(total_weight, dtype=complex))
    if H.shape != M0.shape or H.ndim != 2 or H.shape[0] != H.shape[1]:
        raise ValueError("H_v and M0 must be same-size square matrices")

    evals, evecs = np.linalg.eigh(M0)
    scale = max(1.0, float(np.max(np.abs(evals))) if evals.size else 1.0)
    seed = evecs[:, evals > tol * scale]
    if seed.size == 0:
        return np.zeros((H.shape[0], 0), dtype=complex)

    B = seed
    for _ in range(H.shape[0]):
        trial = np.concatenate([B, H @ B], axis=1)
        U, s, _ = np.linalg.svd(trial, full_matrices=False)
        rank = int(np.sum(s > tol * max(1.0, s[0])))
        B_new = U[:, :rank]
        if B_new.shape[1] == B.shape[1]:
            B = B_new
            break
        B = B_new
    return B


