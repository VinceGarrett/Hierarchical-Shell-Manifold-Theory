@dataclass
class Report:
    ok: bool
    checks: dict[str, bool]
    details: dict[str, float | str]


def admissibility(
    measure: OperatorSpectralMeasure,
    H_v: ArrayLike | None = None,
    scale: float = 1.0,
) -> Report:
    checks: dict[str, bool] = {}
    details: dict[str, float | str] = {}

    # Atomic positivity.
    checks["atoms_hermitian"] = all(_is_hermitian(W) for _, W in measure.atoms)
    checks["atoms_psd"] = all(_is_psd(W) for _, W in measure.atoms)

    # Density positivity on an interior grid.
    if measure.density is not None:
        a, b = measure.support
        if np.isfinite(a) and np.isfinite(b) and b > a:
            x = np.linspace(a, b, 101)[1:-1]
            rho = np.asarray(measure.density(x), dtype=complex)
            herm = []
            psd = []
            for R in rho:
                herm.append(_is_hermitian(R, tol=1e-8))
                psd.append(_is_psd(R, tol=1e-8))
            checks["density_hermitian"] = all(herm)
            checks["density_psd"] = all(psd)
        else:
            checks["density_hermitian"] = False
            checks["density_psd"] = False
    else:
        checks["density_hermitian"] = True
        checks["density_psd"] = True

    # Upper-half-plane sign of Sigma.
    test_z = np.array([-1.7 + 0.2j, -0.2 + 0.7j, 1.3 + 1.1j, 2.1 + 0.4j])
    try:
        S = sigma(measure, test_z, scale=scale)
        nsd = [_is_nsd(_imaginary_part(Si), tol=1e-8) for Si in S]
        checks["im_sigma_nsd"] = all(nsd)
    except Exception:
        checks["im_sigma_nsd"] = False

    # Finite weight, high-energy asymptotics, and matrix Hankel positivity.
    finite_support = np.isfinite(measure.support[0]) and np.isfinite(measure.support[1])
    finite_weight = bool(measure.finite_weight is not False and finite_support)
    checks["finite_weight_completion"] = finite_weight

    if finite_weight:
        try:
            M0 = measure.total_weight_matrix()
            checks["total_weight_psd"] = _is_psd(M0, tol=1e-8)
            z_hi = 80.0 + 7.0j
            S_hi = sigma(measure, z_hi, scale=scale)
            target = scale * M0
            denom = max(1e-12, float(np.linalg.norm(target)))
            rel = float(np.linalg.norm(z_hi * S_hi - target) / denom)
            checks["high_energy_1_over_z"] = rel < 0.08
            details["high_energy_relative_error"] = rel

            moms = measure.moments(4)
            H1 = _stack_block_hankel(moms, order=1)
            checks["block_hankel_psd"] = _is_psd(H1, tol=1e-7)
        except Exception as exc:
            checks["total_weight_psd"] = False
            checks["high_energy_1_over_z"] = False
            checks["block_hankel_psd"] = False
            details["finite_weight_error"] = str(exc)
    else:
        checks["total_weight_psd"] = False
        checks["high_energy_1_over_z"] = False
        checks["block_hankel_psd"] = False

    # If H_V is supplied, visible spectral density should be PSD on sample points.
    if H_v is not None and finite_support:
        try:
            a, b = measure.support
            if b > a:
                E = np.linspace(a, b, 7)[1:-1]
            else:
                E = np.array([a - 0.2, a + 0.2])
            A = visible_spectral_density(H_v, measure, E, scale=scale, eta=1e-3)
            checks["visible_spectral_density_psd"] = all(
                _is_psd(Ai, tol=1e-7) for Ai in A
            )
        except Exception as exc:
            checks["visible_spectral_density_psd"] = False
            details["visible_density_error"] = str(exc)

    # For a finite completion, all checks should pass.
    if finite_weight:
        ok = all(checks.values())
    else:
        # Infinite-weight measures are not accepted as bounded-coupling completions.
        ok = False

    return Report(ok=bool(ok), checks=checks, details=details)


# ---------------------------------------------------------------------------
# Benchmarks
# ---------------------------------------------------------------------------

def run_benchmarks() -> list[tuple[str, bool, str]]:
    results: list[tuple[str, bool, str]] = []

    # 1. Exact two-channel atomic Stieltjes transform.
    W1 = np.array([[0.6, 0.15], [0.15, 0.25]], dtype=float)
    W2 = np.array([[0.2, -0.05], [-0.05, 0.35]], dtype=float)
    mu = atomic_operator_measure(2, [(-0.8, W1), (1.4, W2)], name="two atoms")
    z = 0.7 + 0.4j
    expected = W1 / (z + 0.8) + W2 / (z - 1.4)
    err = np.max(np.abs(sigma(mu, z) - expected))
    results.append(("operator atom Stieltjes", err < 1e-12, f"err={err:.2e}"))

    # 2. Matrix inverse step recovers Sigma.
    H = np.array([[0.25, 0.12], [0.12, 1.05]], dtype=float)
    z_grid = np.array([-0.4 + 0.2j, 0.5 + 0.15j, 1.8 + 0.3j])
    G = propagator(H, mu, z_grid)
    S_hat = inverse_sigma(G, z_grid, H)
    S = sigma(mu, z_grid)
    err = np.max(np.abs(S_hat - S))
    results.append(("matrix inverse Sigma", err < 1e-10, f"err={err:.2e}"))

    # 3-5. Unitary covariance of Sigma, G, and K.
    th = 0.37
    U = np.array([[np.cos(th), -np.sin(th)], [np.sin(th), np.cos(th)]], dtype=complex)
    mu_u = unitary_transform_measure(mu, U)
    H_u = U @ H @ U.conj().T

    zc = 0.3 + 0.55j
    lhs = sigma(mu_u, zc)
    rhs = U @ sigma(mu, zc) @ U.conj().T
    err_s = np.max(np.abs(lhs - rhs))
    results.append(("Sigma unitary covariance", err_s < 1e-10, f"err={err_s:.2e}"))

    lhs = propagator(H_u, mu_u, zc)
    rhs = U @ propagator(H, mu, zc) @ U.conj().T
    err_g = np.max(np.abs(lhs - rhs))
    results.append(("G unitary covariance", err_g < 1e-10, f"err={err_g:.2e}"))

    t = np.array([0.0, 0.7, 1.3])
    lhs = memory(mu_u, t)
    rhs = np.einsum("ab,...bc,dc->...ad", U, memory(mu, t), U.conj())
    err_k = np.max(np.abs(lhs - rhs))
    results.append(("K unitary covariance", err_k < 1e-10, f"err={err_k:.2e}"))

    # 6. A valid matrix measure passes the operator admissibility package.
    W = np.array([[1.0, 0.25], [0.25, 0.5]], dtype=float)
    mu_sc = scalar_weighted_semicircle(W, a=0.9, b=0.2)
    H_sc = np.array([[0.0, 0.2], [0.2, 0.8]], dtype=float)
    rep = admissibility(mu_sc, H_v=H_sc)
    results.append(("matrix PSD measure admissible", rep.ok, str(rep.checks)))

    # 7. Negative operator atom is rejected.
    W_bad = np.diag([1.0, -0.1])
    bad = atomic_operator_measure(2, [(0.0, W_bad)], name="negative operator atom")
    rep_bad = admissibility(bad)
    results.append((
        "negative operator atom rejected",
        (not rep_bad.checks["atoms_psd"]) and (not rep_bad.ok),
        str(rep_bad.checks["atoms_psd"]),
    ))

    # 8. A rank-one coupling leaves an exactly dark visible channel if H_V does not mix it.
    W_dark = np.diag([0.7, 0.0])
    mu_dark = atomic_operator_measure(2, [(0.5, W_dark)], name="rank-one contact")
    H_dark = np.diag([0.1, 1.3])
    zc = 0.9 + 0.2j
    S_dark = sigma(mu_dark, zc)
    G_dark = propagator(H_dark, mu_dark, zc)
    target22 = 1.0 / (zc - 1.3)
    dark_ok = (
        abs(S_dark[1, 1]) < 1e-12
        and abs(S_dark[0, 1]) < 1e-12
        and abs(G_dark[1, 1] - target22) < 1e-12
        and abs(G_dark[0, 1]) < 1e-12
    )
    results.append(("dark visible channel stays free", dark_ok, f"G22err={abs(G_dark[1,1]-target22):.2e}"))

    # 9-10. Visible coupled-subspace rank is 1 without mixing and grows to 2 with mixing.
    M0_dark = mu_dark.total_weight_matrix()
    B1 = visible_coupled_basis(H_dark, M0_dark)
    results.append(("visible coupled rank=1 without mixing", B1.shape[1] == 1, f"rank={B1.shape[1]}"))

    H_mix = np.array([[0.1, 0.18], [0.18, 1.3]], dtype=float)
    B2 = visible_coupled_basis(H_mix, M0_dark)
    results.append(("visible coupled rank=2 with H_V mixing", B2.shape[1] == 2, f"rank={B2.shape[1]}"))

    # 11. K(0) equals the total spectral weight M0.
    K0 = memory(mu_sc, np.array([0.0]), n=8000)[0]
    M0 = mu_sc.total_weight_matrix(n=8000)
