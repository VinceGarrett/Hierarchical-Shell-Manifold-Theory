"""Effective HSMT calculator v0.3.

Finite-dimensional matrix/operator-valued visible sector.

This layer generalizes the verified scalar v0.1 engine to a finite-dimensional
visible Hilbert space with a positive operator-valued spectral measure.

No new foundational assumption:
- H_V is an input.
- dM(E) is an input.
- the visible basis/probe choice is an input.
- no physical channel map iota is included.
- the calculus does not select a measure, d, N, a wall, or a Gaussian.
- v0.2 pair/Kerr dynamics remain a separate modular layer.

Contract
--------
Inputs:
    H_V, positive operator-valued spectral measure dM(E),
    optional complex probe point z or real energy/time grids.

Outputs:
    Sigma(z), matrix propagator G_V(z), matrix visible spectral density,
    operator memory kernel K(t), inverse Sigma from G, moments/Hankel tests,
    admissibility report, and the H_V-cyclic visible subspace generated by
    the range of the total spectral weight M_0.

The "visible coupled subspace" here is a finite-dimensional visible-space
diagnostic. It is not claimed to reconstruct the full hidden cyclic
realization.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

import numpy as np
from numpy.typing import ArrayLike


MatrixDensity = Callable[[np.ndarray], np.ndarray]
MatrixStieltjes = Callable[[np.ndarray], np.ndarray]


# ---------------------------------------------------------------------------
# Basic linear algebra
# ---------------------------------------------------------------------------

def _hermitian_part(A: np.ndarray) -> np.ndarray:
    return 0.5 * (A + np.swapaxes(A.conj(), -1, -2))


def _imaginary_part(A: np.ndarray) -> np.ndarray:
    """Matrix imaginary part (A-A^*)/(2i), Hermitian by construction."""
    return (A - np.swapaxes(A.conj(), -1, -2)) / (2j)


def _is_hermitian(A: np.ndarray, tol: float = 1e-10) -> bool:
    return bool(np.max(np.abs(A - A.conj().T)) <= tol)


def _is_psd(A: np.ndarray, tol: float = 1e-10) -> bool:
    H = _hermitian_part(np.asarray(A, dtype=complex))
    scale = max(1.0, float(np.linalg.norm(H, ord=2)))
    return bool(np.min(np.linalg.eigvalsh(H)) >= -tol * scale)


def _is_nsd(A: np.ndarray, tol: float = 1e-10) -> bool:
    return _is_psd(-np.asarray(A, dtype=complex), tol=tol)


def _stack_block_hankel(moments: list[np.ndarray], order: int) -> np.ndarray:
    return np.block(
        [[moments[i + j] for j in range(order + 1)]
         for i in range(order + 1)]
    )


