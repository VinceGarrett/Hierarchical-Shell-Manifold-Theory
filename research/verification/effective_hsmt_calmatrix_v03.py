@dataclass
class OperatorSpectralMeasure:
    """Positive operator-valued measure on the real line.

    density(E):
        For an array E of shape (n,), returns shape (n, dim, dim).
        Each matrix should be Hermitian positive semidefinite.

    atoms:
        List of (energy, positive-semidefinite matrix weight).

    stieltjes(z):
        Optional analytic implementation returning shape z.shape+(dim,dim).
    """

    name: str
    dim: int
    support: tuple[float, float]
    density: MatrixDensity | None = None
    atoms: list[tuple[float, np.ndarray]] | None = None
    stieltjes: MatrixStieltjes | None = None
    finite_weight: bool | None = None

    def __post_init__(self):
        if self.atoms is None:
            self.atoms = []
        clean = []
        for energy, weight in self.atoms:
            W = np.asarray(weight, dtype=complex)
            if W.shape != (self.dim, self.dim):
                raise ValueError("atom weight has wrong matrix dimension")
            clean.append((float(energy), W))
        self.atoms = clean

    def total_weight_matrix(self, n: int = 5000) -> np.ndarray:
        if not np.isfinite(self.support[0]) or not np.isfinite(self.support[1]):
            raise ValueError("finite total-weight matrix requires a finite-support completion")
        M0 = np.zeros((self.dim, self.dim), dtype=complex)
        for _, W in self.atoms:
            M0 += W
        if self.density is not None:
            a, b = self.support
            if b > a:
                x = np.linspace(a, b, n)
                rho = np.asarray(self.density(x), dtype=complex)
                if rho.shape != (n, self.dim, self.dim):
                    raise ValueError("density returned the wrong shape")
                M0 += np.trapezoid(rho, x, axis=0)
        return _hermitian_part(M0)

    def moments(self, n_moments: int = 4, n: int = 5000) -> list[np.ndarray]:
        a, b = self.support
        if not np.isfinite(a) or not np.isfinite(b):
            raise ValueError("moments require a finite-support completion")
        out = [np.zeros((self.dim, self.dim), dtype=complex)
               for _ in range(n_moments)]
        if self.density is not None and b > a:
            x = np.linspace(a, b, n)
            rho = np.asarray(self.density(x), dtype=complex)
            if rho.shape != (n, self.dim, self.dim):
                raise ValueError("density returned the wrong shape")
            for k in range(n_moments):
                out[k] += np.trapezoid(
                    (x**k)[:, None, None] * rho, x, axis=0
                )
        for energy, W in self.atoms:
            for k in range(n_moments):
                out[k] += (energy**k) * W
        return [_hermitian_part(M) for M in out]


def atomic_operator_measure(
    dim: int,
    atoms: list[tuple[float, ArrayLike]],
    name: str = "operator atoms",
) -> OperatorSpectralMeasure:
    clean = [(float(e), np.asarray(W, dtype=complex)) for e, W in atoms]

    def analytic(z):
        z = np.asarray(z, dtype=complex)
        out = np.zeros(z.shape + (dim, dim), dtype=complex)
        for e, W in clean:
            out += W / (z[..., None, None] - e)
        return out

    energies = [e for e, _ in clean]
    lo = min(energies) if energies else 0.0
    hi = max(energies) if energies else 0.0
    return OperatorSpectralMeasure(
        name=name,
        dim=dim,
        support=(lo, hi),
        atoms=clean,
        stieltjes=analytic,
        finite_weight=True,
    )


def scalar_weighted_semicircle(
    weight: ArrayLike,
    a: float = 1.0,
    b: float = 0.0,
    name: str = "matrix semicircle",
) -> OperatorSpectralMeasure:
    """Normalized semicircle multiplied by a fixed PSD matrix weight."""
    W = np.asarray(weight, dtype=complex)
    dim = W.shape[0]
    if W.shape != (dim, dim):
        raise ValueError("weight must be square")
    lo, hi = b - 2 * a, b + 2 * a

    def density(E):
        E = np.asarray(E, dtype=float)
        rad = np.clip(4 * a**2 - (E - b)**2, 0.0, None)
        scalar = np.sqrt(rad) / (2 * np.pi * a**2)
        return scalar[..., None, None] * W

    def stieltjes_analytic(z):
        z = np.asarray(z, dtype=complex)
        disc = (z - b)**2 - 4 * a**2
        root = np.sqrt(disc)
        # Choose the root so m(z)~1/z and Im m<=0 in the upper half-plane.
        sign_ref = np.sign(np.real(z - b) + 1e-15)
        branch = np.where(np.real(root) * sign_ref < 0, -root, root)
        m = ((z - b) - branch) / (2 * a**2)
        flip = (np.imag(z) > 0) & (np.imag(m) > 0)
        m = np.where(flip, ((z - b) + branch) / (2 * a**2), m)
        return m[..., None, None] * W

    return OperatorSpectralMeasure(
        name=name,
        dim=dim,
        support=(lo, hi),
        density=density,
        stieltjes=stieltjes_analytic,
        finite_weight=True,
    )


def unitary_transform_measure(
    measure: OperatorSpectralMeasure,
    U: ArrayLike,
    name: str | None = None,
) -> OperatorSpectralMeasure:
    """Transform the visible basis: dM -> U dM U^*."""
    U = np.asarray(U, dtype=complex)
    if U.shape != (measure.dim, measure.dim):
        raise ValueError("unitary has wrong dimension")
    I = np.eye(measure.dim)
    if np.max(np.abs(U.conj().T @ U - I)) > 1e-9:
        raise ValueError("U must be unitary")

    def density(E):
        rho = np.asarray(measure.density(E), dtype=complex)
        return np.einsum("ab,...bc,dc->...ad", U, rho, U.conj())

    def analytic(z):
        S = stieltjes(measure, z)
        return np.einsum("ab,...bc,dc->...ad", U, S, U.conj())

    atoms = [(e, U @ W @ U.conj().T) for e, W in measure.atoms]
    return OperatorSpectralMeasure(
        name=name or f"{measure.name} rotated",
        dim=measure.dim,
        support=measure.support,
        density=density if measure.density is not None else None,
        atoms=atoms,
        stieltjes=analytic,
        finite_weight=measure.finite_weight,
    )


